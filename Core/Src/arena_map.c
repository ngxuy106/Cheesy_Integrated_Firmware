float Map_DistToStaticObstacleCm(float x_cm, float y_cm)
{
    /* 1. Khoang cach toi 3 tuong bien (Trai x=0, Phai x=180, Tren y=120) */
    float min_d = 999.0f;
    float d_left  = (x_cm <= 0.0f)   ? 0.0f : x_cm;
    float d_right = (x_cm >= 180.0f) ? 0.0f : (180.0f - x_cm);
    float d_top   = (y_cm >= 120.0f) ? 0.0f : (120.0f - y_cm);

    if (d_left  < min_d) min_d = d_left;
    if (d_right < min_d) min_d = d_right;
    if (d_top   < min_d) min_d = d_top;

    /* 2. Khoi chu U cam di tat: x in [60, 120], y in [0, 60] */
    float d_u = dist_point_to_box(x_cm, y_cm, 60.0f, 0.0f, 120.0f, 60.0f);
    if (d_u < min_d) min_d = d_u;

    /* 3. 17 coc vat can tinh T1..T17 (10x10cm -> +/- 5cm quanh tam) */
    for (int i = 0; i < NUM_STD_OBSTACLES; i++) {
        float cx = (float)OBSTACLES_STD[i].center_x_mm * 0.1f;
        float cy = (float)OBSTACLES_STD[i].center_y_mm * 0.1f;
        float d = dist_point_to_box(x_cm, y_cm, cx - 5.0f, cy - 5.0f, cx + 5.0f, cy + 5.0f);
        if (d < min_d) {
            min_d = d;
        }
    }

    return min_d;
}
