bool Map_IsObstacle(int row, int col)
{
    if (row < 0 || row >= MAP_NY || col < 0 || col >= MAP_NX) {
        return true;
    }
    return (s_arena_grid[row][col] != CELL_FREE);
}

bool Map_IsBlocked(int32_t x_mm, int32_t y_mm)
{
    int32_t min_coord = -MAP_CELL_MM;
    int32_t max_x = (MAP_NX - MAP_MARGIN) * MAP_CELL_MM;
    int32_t max_y = (MAP_NY - MAP_MARGIN) * MAP_CELL_MM;
    if (x_mm < min_coord || x_mm > max_x || y_mm < min_coord || y_mm > max_y) {
        return true;
    }
    int ix = (int)floorf(((float)x_mm + (float)(MAP_MARGIN * MAP_CELL_MM)) / (float)MAP_CELL_MM);
    int iy = (int)floorf(((float)y_mm + (float)(MAP_MARGIN * MAP_CELL_MM)) / (float)MAP_CELL_MM);
    return Map_IsObstacle(iy, ix);
}

bool Map_IsBlockedCm(float x_cm, float y_cm)
{
    return Map_IsBlocked((int32_t)roundf(x_cm * 10.0f), (int32_t)roundf(y_cm * 10.0f));
}

bool Map_IsFinishLineCrossed(float x_cm, float y_cm)
{
    return (x_cm >= GOAL_X_MIN && x_cm <= GOAL_X_MAX && y_cm <= GOAL_FINISH_Y);
}

